def _build_outputs(func_name, returns, template=None, primary=None, variant=0,
                   preserved=None):
	custom = _by_variant(OUTPUT_DISPLAY_NAMES, func_name, variant)
	names = [_OUTPUT_BUILDERS[k][1] for k in returns]
	outputs = []
	for i, kind in enumerate(returns):
		builder, name = _OUTPUT_BUILDERS[kind]
		if custom is not None:
			name = custom[i]
		elif names.count(name) > 1:
			name = f"{name}_{i}"
		if kind == "image" and template is not None and _echoes(preserved, i):
			if custom is None:
				name = "result"
			outputs.append(polytype.match_output(template, name,
				tooltip=f"Echoes the '{primary}' input's format: an IMAGE link "
				        "comes back as IMAGE, MASK as MASK, NPARRAY stays NPARRAY."))
		elif kind in _OUTPUT_TOOLTIPS:
			ret_doc = RETURN_DOCS.get(func_name)
			if not ret_doc:
				for pn in _OUTPUT_PARAM_NAMES:
					ret_doc = PARAM_DOCS.get((func_name, pn))
					if ret_doc:
						break
			if not ret_doc:
				ret_doc = "- - -"
			outputs.append(builder(display_name=name,
				tooltip=f"{ret_doc}\n\n{_OUTPUT_TOOLTIPS[kind]}"))
		else:
			outputs.append(builder(display_name=name))
	return outputs


def _composite_out(kind, value):
	"""cv2's composite return value -> what its typed socket carries.

	`None` never reaches a caller as `None`: a detection-style function that
	found nothing still has to emit something the next node can read (rule 4).
	"""
	if kind == "scalar" or kind == "range":
		# ONE literal string, the spelling scalars.py parses and every colour /
		# borderValue input takes (the same decision as the scalar INPUTS)
		return repr(tuple(value) if value is not None else (0.0, 0.0, 0.0, 0.0))
	if value is None:
		return {"x": 0, "y": 0, "width": 0, "height": 0} if kind == "rect" \
			else ([] if kind != "moments" else tuples.parse_moments(
				{k: 0.0 for k in tuples.MOMENT_KEYS}))
	if kind == "point2i" or kind == "size":
		return [int(v) for v in value]
	if kind == "point2f":
		return [float(v) for v in value]
	if kind == "rect":
		# core's BOUNDING_BOX, nested one group per frame like every other
		# bbox emitter in this pack (boxpolicy.nest)
		return boxpolicy.nest([tuples.rect_to_bbox(value)])
	if kind == "rotatedrect":
		return tuples.parse_rotated_rect(value)
	if kind == "moments":
		return tuples.parse_moments(value)
	return repr(value)


def _parse_composite(kind, value, pname):
	"""A typed composite INPUT's value -> what cv2 takes, whatever it arrived as.

	Both kinds accept their own typed link, the literal string the widget still
	holds, and (for a RotatedRect) the flat 5-number spelling.
	"""
	if kind == "rotatedrect":
		return tuples.parse_rotated_rect(value, pname)
	return tuples.parse_moments(value, pname)


def _parse_literal(value: str, pname: str):
	text = value.strip()
	lowered = text.lower()
	if lowered in ("true", "false"):
		return lowered == "true"
	try:
		return literal_eval(text)
	except (ValueError, SyntaxError) as e:
		raise ValueError(
			f'Parameter "{pname}" is not a valid Python literal: "{value}". '
			f"Examples: 3, 1.5, (3, 3). ({e})"
		) from e


def _describe(value):
	if isinstance(value, np.ndarray):
		return f"ndarray{value.shape} {value.dtype}"
	return repr(value)[:80]


def _to_gray(value):
	"""BGR -> single channel for a GRAY_REQUIRED param.

	Takes either one resolved array or the LIST of frames the frame-batch path
	builds, so the conversion applies identically in both modes."""
	if isinstance(value, list):
		return [_to_gray(v) for v in value]
	if isinstance(value, np.ndarray) and value.ndim == 3 and value.shape[2] == 3:
		return cv2.cvtColor(value, cv2.COLOR_BGR2GRAY)
	return value


def _echo_dtype(value, dtype):
	"""Re-cast an image result to the caller's input dtype (the cv2 ft module
	hardcodes CV_32F output regardless of the input depth). Integer targets are
	rounded and clipped to the dtype's range so 0-255 float data survives the
	cast; float targets are a plain astype."""
	if np.issubdtype(dtype, np.integer):
		info = np.iinfo(dtype)
		return np.clip(np.rint(value), info.min, info.max).astype(dtype)
	return value.astype(dtype)


def _run_cv_offloaded(func_name, jobs):
	"""Run resolved cv2 call(s) in an interruptible subprocess (OFFLOAD_WHEN).

	`jobs` is a list of {'args': [...], 'kwargs': {...}, 'ret_slot': ...}
	payloads (see workers/cv_call_worker.py). The shared workerutils loop
	polls the worker every 0.5s; on ComfyUI cancel the worker is terminated
	(killed if it does not stop within 10s) and InterruptProcessingException
	is RE-RAISED so the whole run aborts - a filter node must not quietly
	continue with a half-computed result. Returns the per-job results, in
	order.
	"""
	tag, payload = workerutils.run_subprocess(
		workerutils.worker_script_path('cv_call_worker.py'),
		{'func_name': func_name, 'jobs': jobs})
	if tag != 'ok':
		raise RuntimeError(f"cv2.{func_name} worker failed:\n{payload}")
	return payload


def _offloaded_call(func_name, args, kwargs, params):
	"""One resolved cv2 call run in the interruptible subprocess.

	Mirrors _returning's buffer splice when the function delivers its result
	through an ARGUMENT (INPLACE_OUT_PARAMS): the pre-allocated buffer is
	inserted at the positional slot cv2 expects and the worker is told to hand
	it back via ret_slot, because the raw call returns None there (xphoto.inpaint).
	"""
	inplace = INPLACE_OUT_PARAMS.get(func_name)
	ret_slot = None
	if inplace is not None:
		_out_name, ref_name, out_index = inplace
		ref = kwargs.get(ref_name)
		if ref is None:
			ref = args[next(i for i, p in enumerate(params)
			               if p[0] == ref_name)]
		buf = np.zeros_like(np.asarray(ref))
		args = tuple(args[:out_index]) + (buf,) + tuple(args[out_index:])
		ret_slot = out_index
	return _run_cv_offloaded(func_name, [{
		'args': list(args), 'kwargs': kwargs, 'ret_slot': ret_slot}])[0]


def _resolve_cv2(func_name):
	"""cv2 callable for a plain ('resize') or dotted ('xphoto.oilPainting')
	registry name, or None when the installed build does not expose it.

	A missing contrib BINARY still leaves the stub PACKAGE importable
	(cv2/xphoto/__init__.pyi ships with every wheel), so `cv2.xphoto` exists but
	is EMPTY - the getattr chain below is what actually detects that, and the node
	is then skipped instead of being built around a function that could only raise
	at execution time. Run tools/repair_opencv_contrib.py if the contrib nodes are
	missing: installing plain opencv-python over opencv-contrib-python(-headless) overwrites
	the shared cv2 binary with the core-only one."""
	obj = cv2
	for part in func_name.split("."):
		obj = getattr(obj, part, None)
		if obj is None:
			return None
	return obj if callable(obj) else None


def _returning(func, inplace, ref_index):
	"""Wrap a cv2 function that returns its result through an ARGUMENT.

	A few contrib functions return None and deliver their result only by writing
	into a buffer the caller must pre-allocate (the whole cv2.intensity_transform
	API, xphoto.dctDenoising, xphoto.inpaint). The registry drops that parameter
	from the node's inputs and declares an image RETURN instead, so the node looks
	like every other filter.

	The wrapper is what makes that true at CALL time: it allocates the buffer with
	the reference argument's shape and dtype (cv2 requires it to be pre-sized - a
	(0, 0) placeholder raises), inserts it at the positional slot cv2 expects, and
	returns it. Doing it here rather than at the call site means the single-frame
	path and the per-frame batch loop - which rebuilds its own argument list from
	the DECLARED params, and so would never carry a spliced-in buffer - both work
	without any special-casing.

	`ref_index` is the reference input's position in the node's own (out-param
	free) argument list, so the buffer is sized from whatever that call actually
	passed rather than assuming it came first.
	"""
	_out_name, ref_name, out_index = inplace

	def call(*args, **kwargs):
		if ref_name in kwargs:
			ref = kwargs[ref_name]
		elif ref_index < len(args):
			ref = args[ref_index]
		else:
			raise ValueError(
				f"cannot size the output buffer: '{ref_name}' was not passed")
		buf = np.zeros_like(np.asarray(ref))
		spliced = tuple(args[:out_index]) + (buf,) + tuple(args[out_index:])
		func(*spliced, **kwargs)
		return buf

	return call


def _make_node(func_name, variant, n_variants, params, returns):
	# Redundant with the generator's BLACKLIST (which already kept these out of
	# the registry) and kept that way on purpose - see HIDDEN_FUNCTIONS.
	if func_name in HIDDEN_FUNCTIONS:
		return None
	func = _resolve_cv2(func_name)
	if func is None:  # not available in the installed OpenCV build
		return None
	# 'xphoto.oilPainting' -> module 'xphoto', bare name 'oilPainting'. The module
	# qualifier is kept in the node id and the display name so a submodule
	# function can never collide with the top-level one of the same name:
	# cv2.inpaint and cv2.xphoto.inpaint are different algorithms whose masks mean
	# OPPOSITE things (see the xphoto.inpaint tooltip).
	module, _, bare_name = func_name.rpartition(".")
	# result-only buffer: not an input, allocated and returned by the wrapper
	# (see registry_contrib.INPLACE_OUT_PARAMS)
	inplace = INPLACE_OUT_PARAMS.get(func_name)
	if inplace is not None:
		func = _returning(func, inplace,
		                  next(i for i, p in enumerate(params) if p[0] == inplace[1]))

	# drawing primitives: rename cv2's canvas param ("img"/"image") to "source"
	# BEFORE anything reads the params list, so the signature, the primary-input
	# detection and execute()'s kwargs all agree on the new name.
	canvas_param = DRAWING_CANVAS.get(func_name)
	if canvas_param is not None:
		params = [(("source" if p == canvas_param else p), k, o)
		          for p, k, o in params]

	eigen_note = ""
	if func_name in EIGEN_GATED:
		eigen_note = _EIGEN_NOTE_PRESENT if HAS_EIGEN else _EIGEN_NOTE_MISSING

	suffix = f"_{variant}" if n_variants > 1 else ""
	node_id = f"cv2_{func_name.replace('.', '_')}{suffix}"
	display = f"cv2.{func_name}" + (f" ({variant + 1}/{n_variants})" if n_variants > 1 else "")
	signature = ", ".join(p[0] + ("?" if p[2] else "") for p in params)
	splits = {p: spec for p, k, o in params
	          if (spec := _split_spec(func_name, p, k)) is not None
	          and k not in COMPOSITE_INPUT_KINDS}
	# families that render as ONE atomic CV_TUPLE input instead (see
	# COMPOSITE_INPUT_KINDS); value -> (component dicts, per-component EnumGroup)
	composites = {p: _composite_spec(spec, p) for p, k, o in params
	              if k in COMPOSITE_INPUT_KINDS
	              and (spec := _split_spec(func_name, p, k)) is not None}

	# type-preserving functions share a MatchType template between their primary
	# image input and the image output(s), so the output socket's type follows
	# whatever the caller links in (core Resize Image/Mask pattern)
	primary = None
	preserve = TYPE_PRESERVING.get(func_name) if "image" in returns else None
	if preserve is not None:
		want = PRIMARY_PARAM.get(func_name)
		for p, k, o in params:
			if (k == "image" and not o
					and (func_name, p) not in OPTIONAL_BUFFER_PARAMS
					and (func_name, p) not in HIDDEN_BUFFER_PARAMS
					and (want is None or p == want)):
				primary = p
				break
	if preserve is not None and func_name in LATENT_OK:
		preserve = polytype.with_latent(preserve)
	template = polytype.match_template(types=preserve) if primary is not None else None
	# which image outputs follow that template (None = all of them)
	preserved = _by_variant(PRESERVED_OUTPUTS, func_name, variant)
	preserved = None if preserved is None else set(preserved)

	def define_schema(cls):
		inputs = []
		for p, k, o in params:
			if (func_name, p) in HIDDEN_BUFFER_PARAMS:
				continue  # cv2 allocates internally; not exposed in UI
			# An OUTPUT_BUFFER_PARAM is a REQUIRED positional argument of cv2
			# that accepts None, so it renders OPTIONAL however the registry
			# marks it (execute() passes it positionally as None when
			# unconnected either way). The registry marks such params required
			# because the cv2 5 stubs annotate them `MatLike | None` with no
			# default - which is not the same thing as an optional argument,
			# and reading it as one shifts every following positional.
			o = bool(o) or (func_name, p) in OPTIONAL_BUFFER_PARAMS
			if p in composites:
				inputs.append(_build_composite_input(
					p, _split_spec(func_name, p, k), bool(o),
					_tooltip_for(func_name, p)))
			elif p in splits:
				inputs.extend(_build_split_inputs(splits[p], bool(o)))
			elif template is not None and p == primary:
				primary_tip = (_tooltip_for(func_name, p) or "") \
					+ " The image output(s) echo this input's format." \
					+ (polytype.LATENT_NOTE if func_name in LATENT_OK else "")
				if p == "dst":
					# cv2 writes its result into the dst array in place; the
					# wrapper copies first (lowlevel.py:994) so the caller's
					# input array is never mutated - surface that to users.
					primary_tip += (" The low-level cv2 function writes its result "
						"into this array in place, but this wrapper passes cv2 a "
						"private copy, so your input array is never modified.")
				inputs.append(polytype.match_input(p, template, tooltip=primary_tip))
			else:
				inputs.append(_build_input(func_name, p, k, bool(o)))
		return io.Schema(
			node_id=node_id,
			display_name=display,
			category=(f"image/CV/low-level/{module}" if module
			          else f"image/CV/low-level/cv2 {bare_name[0].upper()}"),
			description=eigen_note
			            + f"Raw wrapper of cv2.{func_name}({signature}). "
			            f"Parameters marked '?' are optional; blank means OpenCV default. "
			            + (f"From the opencv-contrib '{module}' module. " if module else "")
			            + "See the OpenCV documentation for details.",
			inputs=inputs,
			outputs=_build_outputs(func_name, returns, template, primary, variant,
			                       preserved),
		)

	def execute(cls, **kwargs):
		# atomic composite params (CV_TUPLE): one value in, whatever spelling it
		# arrived in - a list from 'CV Tuple', the '(w, h)' literal the widget
		# saves (and every workflow saved before the components were split), an
		# NPARRAY vector, or a bounding-box dict
		for p, (components, resolvers) in composites.items():
			if p not in kwargs:
				continue
			parts = tuples.parse(kwargs[p], components, p)
			kwargs[p] = tuple(
				enum.resolve(v) if enum is not None else v
				for v, enum in zip(parts, resolvers))
		# reassemble split composite params (Size/Point/...) from their components
		for p, spec in splits.items():
			comps = [c[0] for c in spec]
			if all(c in kwargs for c in comps):
				kwargs[p] = tuple(
					enum.resolve(kwargs.pop(name)) if enum is not None
					else (float if is_f else int)(kwargs.pop(name))
					for name, _d, _m, is_f, _t, enum in spec)
			elif isinstance(kwargs.get(p), str) and kwargs[p].strip():
				# back-compat: a workflow saved before this param was split still
				# carries the whole "(x, y)" literal under the original name
				kwargs[p] = _parse_literal(kwargs[p], p)
		# Detect batch mode from the primary input.
		# LATENT_BATCH_SAFE: arithmetic ops that accept [B,...,C] directly —
		#   the full batch flows through to cv2 without frame extraction.
		# FRAME_BATCH_SAFE: spatial ops — each frame is extracted, processed
		#   independently, and results are re-stacked into a batch.
		# IMAGE_ONLY_BATCH guards: some FRAME_BATCH_SAFE functions require
		#   3-channel BGR; skip batch mode for MASK (single-channel) inputs.
		batch_mode = False
		frame_batch = False
		_batch_size = 0
		if primary is not None:
			pv = kwargs.get(primary)
			if isinstance(pv, torch.Tensor) and pv.ndim in (3, 4) \
					and pv.shape[0] == 0:
				# An EMPTY batch is a valid input: "0 connected components",
				# "0 detections" etc. produce a 0-frame IMAGE/MASK batch, and a
				# spatial op over no frames is no frames - never a crash (frame
				# 0 of an empty batch would raise). Non-image outputs have no
				# per-frame value to report, so they come back as None - and so
				# does an image output that does NOT echo the input (its socket
				# is NPARRAY; handing it a tensor would be a type lie).
				return io.NodeOutput(*[
					pv.clone() if (k == "image" and _echoes(preserved, i)) else None
					for i, k in enumerate(returns)])
			is_latent_batch = (func_name in LATENT_BATCH_SAFE
			                   and polytype.is_latent(pv)
			                   and pv["samples"].ndim == 4
			                   and pv["samples"].shape[0] > 1)
			is_tensor_batch = (isinstance(pv, torch.Tensor)
			                   and pv.ndim in (3, 4) and pv.shape[0] > 1)
			if is_latent_batch or is_tensor_batch:
				_batch_size = pv.shape[0] if isinstance(pv, torch.Tensor) \
					else pv["samples"].shape[0]
				if func_name in LATENT_BATCH_SAFE:
					batch_mode = True  # pass [B,...,C] directly to cv2
				elif func_name in FRAME_BATCH_SAFE:
					# IMAGE_ONLY_BATCH guard: skip batch mode if the primary
					# input is a MASK and the function needs 3-channel BGR.
					is_mask = (isinstance(pv, torch.Tensor) and pv.ndim in (3, 4)
					           and (pv.ndim == 3 or pv.shape[-1] == 1))
					if not (is_mask and func_name in IMAGE_ONLY_BATCH):
						batch_mode = True
						frame_batch = True
		args = []
		call_kwargs = {}
		out_tag = "nparray"  # format the image outputs are restored to
		primary_dtype = None  # resolved input dtype, for OUTPUT_DTYPE_MATCH casts
		for pname, kind, optional in params:
			enum = _enum_for(func_name, pname, kind)
			value = kwargs.get(pname)
			if isinstance(value, torch.Tensor) or polytype.is_latent(value):
				# a ComfyUI IMAGE/MASK/LATENT linked straight into an image
				# socket: convert to the ndarray cv2 expects (uint8 BGR /
				# uint8 [H,W] / float32 [H,W,C] respectively).
				if frame_batch and isinstance(value, torch.Tensor) \
						and value.ndim in (3, 4):
					# FRAME_BATCH_SAFE: extract all frames for per-frame loop.
					# IMAGE [B,H,W,C] -> list of uint8 BGR [H,W,3];
					# MASK [B,H,W] or [B,1,H,W] -> list of uint8 [H,W].
					if value.ndim == 4 and value.shape[-1] in (1, 3, 4):
						# IMAGE batch [B,H,W,C]
						frames = imageutils.image_batch_to_bgr(value)
						value = frames  # keep as list for batch loop
						tag = "image"
					else:
						# MASK batch [B,H,W] or [B,1,H,W]
						frames = imageutils.mask_batch_to_u8(value)
						value = frames  # keep as list for batch loop
						tag = "mask"
				elif batch_mode and isinstance(value, torch.Tensor) \
						and value.ndim == 4:
					# LATENT_BATCH_SAFE: keep full [B,...,C] shape
					frames = imageutils.image_batch_to_bgr(value)
					value = np.stack(frames, axis=0)
					tag = "image"
				elif batch_mode and polytype.is_latent(value):
					value, tag = polytype.resolve_batch(value)
				else:
					value, tag = polytype.resolve(value)
				if pname == primary:
					out_tag = tag
				if tag == "image" and (func_name, pname) in GRAY_REQUIRED:
					# this cv2 function only accepts single-channel input.
					# In frame_batch mode `value` is the LIST of frames - the
					# conversion has to reach every one of them, or a
					# multi-frame IMAGE batch hands cv2 the 3-channel array it
					# rejects (adaptiveThreshold/equalizeHist/spatialGradient/
					# preCornerDetect/demosaicing are in both tables).
					value = _to_gray(value)
			if pname == primary and func_name in OUTPUT_DTYPE_MATCH:
				# cv2's ft module hardcodes CV_32F output; remember the resolved
				# input dtype so the result can be cast back to it (below)
				if isinstance(value, np.ndarray):
					primary_dtype = value.dtype
				elif isinstance(value, list) and value \
						and isinstance(value[0], np.ndarray):
					primary_dtype = value[0].dtype
			if isinstance(value, np.ndarray):
				# many cv2 functions write into their arguments (watershed's
				# markers, randn/randu's dst, every drawing primitive's img...);
				# a mutated input is another node's cached output, which must
				# stay immutable - so every array crosses as a private copy
				value = value.copy()
			if (kind == "int" and enum is None and not isinstance(value, bool)
					and isinstance(value, (int, float, np.integer, np.floating))):
				# an INT-kind cv2 arg fed from a FLOAT-valued socket (e.g.
				# cv2.circle's radius from an EnclosingCircle) must reach cv2 as a
				# real int - cv2 rejects a float radius/thickness/count with an
				# opaque "Overload resolution failed". Split components already
				# coerce; do the same for plain int params.
				value = int(value)
			if (func_name, pname) in OPTIONAL_BUFFER_PARAMS:
				# pass the user's array, or None when unconnected (cv2 allocates an
				# output buffer / treats it as "no distortion" etc.); omitting it
				# would shift the remaining positional arguments
				args.append(value if isinstance(value, np.ndarray) else None)
				continue
			if (func_name, pname) in HIDDEN_BUFFER_PARAMS:
				# fully hidden output buffer — always let cv2 allocate
				args.append(None)
				continue
			if pname in splits:
				# value is the tuple reassembled from the component widgets above
				if optional:
					call_kwargs[pname] = value
				else:
					args.append(value)
				continue
			if optional:
				if value is None:
					continue
				if enum is not None:
					if str(value).strip() == "":
						continue  # workflows saved before this param became a dropdown
					call_kwargs[pname] = enum.resolve(value)
				elif kind == "rotatedrect" or kind == "moments":
					# blank widget = omit; a link carries the typed value itself
					if isinstance(value, str) and not value.strip():
						continue
					call_kwargs[pname] = _parse_composite(kind, value, pname)
				elif kind == "image" or kind == "any":
					call_kwargs[pname] = value
				elif kind == "scalar":
					# blank = OpenCV default; anything else is a Scalar literal
					# ("(0, 255, 0)" / "255"), or a bare number when the widget
					# was converted to an input - both broadcast the same way
					if isinstance(value, str) and not value.strip():
						continue
					call_kwargs[pname] = scalars.parse_scalar(value, pname)
				elif isinstance(value, (int, float, bool)):
					call_kwargs[pname] = value  # typed widget (curated default)
				else:
					if str(value).strip() == "":
						continue  # blank = OpenCV default (also old saved workflows)
					call_kwargs[pname] = _parse_literal(str(value), pname)
			else:
				if enum is not None:
					args.append(enum.resolve(value))
				elif kind == "scalar":
					if isinstance(value, str) and not value.strip():
						raise ValueError(
							f'Parameter "{pname}" is required. {scalars.SCALAR_TOOLTIP}')
					args.append(scalars.parse_scalar(value, pname))
				elif kind == "rotatedrect" or kind == "moments":
					args.append(_parse_composite(kind, value, pname))
				elif kind == "literal" or kind in COMPOSITE_KINDS:
					if str(value).strip() == "":
						raise ValueError(f'Parameter "{pname}" is required. {LITERAL_TOOLTIP}')
					args.append(_parse_literal(str(value), pname))
				else:
					args.append(value)

		# --- call cv2 ---------------------------------------------------------
		# OFFLOAD_WHEN: run the slowest mode(s) of a cv2 call in an
		# interruptible subprocess so ComfyUI can cancel mid-call. Matched on
		# the widget label AFTER the arg loop so enum/split resolution already
		# happened and the subprocess receives fully resolved arguments.
		offload = False
		if func_name in OFFLOAD_WHEN:
			_pn, _label = OFFLOAD_WHEN[func_name]
			offload = str(kwargs.get(_pn)) == _label
		elif func_name in OFFLOAD_ALWAYS:
			offload = True
		if frame_batch:
			# FRAME_BATCH_SAFE: loop per-frame.  Image params are lists of
			# frames (extracted above); non-image params are scalars/enums.
			# Each frame[i] of every image param goes together; scalar params
			# are reused as-is for every frame.
			# Rebuild a name -> resolved-value lookup from the final args list.
			# Params in args: OUTPUT_BUFFER/HIDDEN_BUFFER (always), and all
			# non-optional params (split or not).  Optional params are in
			# call_kwargs or were skipped.
			_arg_names = []
			for pn, pk, po in params:
				if (func_name, pn) in OPTIONAL_BUFFER_PARAMS \
						or (func_name, pn) in HIDDEN_BUFFER_PARAMS:
					_arg_names.append(pn)
				elif not po:
					_arg_names.append(pn)
			_arg_map = dict(zip(_arg_names, args))
			_arg_map.update(call_kwargs)
			batch_results = None
			for fi in range(_batch_size):
				frame_args = []
				frame_kw = {}
				for pname, kind, optional in params:
					av = _arg_map.get(pname)
					if isinstance(av, list):
						av = av[fi].copy()  # copy: cv2 modifies in-place
					elif isinstance(av, np.ndarray):
						av = av.copy()
					if pname in call_kwargs:
						frame_kw[pname] = av
					elif not optional:
						frame_args.append(av)
					# else: an optional param that was SKIPPED (blank =
					# OpenCV default) - it must not become a None positional
				try:
					if offload:
						frame_result = _offloaded_call(
							func_name, frame_args, frame_kw, params)
					else:
						frame_result = func(*frame_args, **frame_kw)
				except cv2.error as e:
					arg_info = ", ".join(_describe(a) for a in frame_args)
					raise RuntimeError(
						f"cv2.{func_name} failed on frame {fi}: {e}\n"
						f"Inputs were: ({arg_info})"
						+ (f" with options {frame_kw}" if frame_kw else "")
					) from e
				frame_values = frame_result \
					if (isinstance(frame_result, tuple) and len(returns) > 1) \
					else (frame_result,)   # same one-composite-return rule
				if batch_results is None:
					batch_results = [[] for _ in frame_values]
				for ri, rv in enumerate(frame_values):
					batch_results[ri].append(rv)
			# Stack per-frame results into batch arrays.
			# Image outputs (ndarray) are stacked into [B,...]; non-image
			# outputs (float, int, literal) are kept as a list (the output
			# handler will format them as-is — typically the value is the
			# same across frames, so the list is fine for display).
			values = tuple(
				np.stack(vlist, axis=0) if isinstance(vlist[0], np.ndarray)
				else vlist
				for vlist in batch_results
			)
		else:
			try:
				if offload:
					result = _offloaded_call(
						func_name, args, call_kwargs, params)
				else:
					result = func(*args, **call_kwargs)
			except cv2.error as e:
				arg_info = ", ".join(_describe(a) for a in args)
				raise RuntimeError(
					f"cv2.{func_name} failed: {e}\n"
					f"Inputs were: ({arg_info})"
					+ (f" with options {call_kwargs}" if call_kwargs else "")
				) from e
			# A cv2 function with ONE return that is itself a tuple (a Rect from
			# boundingRect, a Scalar from mean, a RotatedRect from fitEllipse)
			# must NOT be splatted into several outputs: zip() against `returns`
			# would keep the first component and drop the rest silently -
			# cv2_boundingRect used to emit "18" for (18, 8, 25, 25).
			values = result if (isinstance(result, tuple) and len(returns) > 1) \
				else (result,)
		out = []
		for oi, (kind, value) in enumerate(zip(returns, values)):
			if (kind == "image" and primary_dtype is not None
					and isinstance(value, np.ndarray)
					and value.dtype != primary_dtype):
				# ft module hardcodes CV_32F output - echo the input's dtype
				# so a uint8 image comes back uint8 like every other filter
				value = _echo_dtype(value, primary_dtype)
			# does this output come back in the caller's format? Its socket is a
			# MatchType only when the schema said so, and PRESERVED_OUTPUTS can
			# exclude one image output of a preserving function (floodFill's mask)
			echo = (kind == "image" and out_tag != "nparray"
			        and isinstance(value, np.ndarray) and _echoes(preserved, oi))
			if kind in COMPOSITE_KINDS:
				# typed composite socket (CV_TUPLE / BOUNDING_BOX /
				# CV_ROTATED_RECT / CV_MOMENTS; a Scalar stays a literal).
				# In frame-batch mode the value is the per-frame LIST, so each
				# frame is converted on its own - a BOUNDING_BOX then carries
				# one group per frame, which is core's own convention.
				if frame_batch and isinstance(value, list):
					if kind == "rect":
						out.append([[tuples.rect_to_bbox(v)] for v in value])
					else:
						out.append([_composite_out(kind, v) for v in value])
				else:
					out.append(_composite_out(kind, value))
			elif kind == "literal":
				out.append(repr(value))
			elif kind == "str":
				out.append(str(value))
			elif echo and value.ndim in (3, 4) and batch_mode:
				# type-preserving function fed a batch: hand the full
				# [B,...,C] or [B,H,W] result back in the caller's format.
				if out_tag == "latent" and value.ndim == 4:
					out.append(polytype.restore_batch(value))
				elif out_tag == "image" and (value.ndim == 3
						or value.shape[-1] in (1, 3, 4)):
					# [B,H,W,C] colour frames OR [B,H,W] single-channel ones -
					# a gray batch (Canny, equalizeHist, adaptiveThreshold over
					# an IMAGE batch) is still an IMAGE to the caller, and
					# bgr_to_image_batch replicates each frame to 3 channels.
					# Without the ndim == 3 case the socket says IMAGE and the
					# node hands back a raw ndarray.
					out.append(imageutils.bgr_to_image_batch(list(value)))
				elif out_tag == "mask" and value.ndim == 3:
					# MASK batch [B,H,W] — restore each frame
					out.append(imageutils.u8_to_mask_batch(
						[f for f in value]))
				else:
					out.append(value)
			elif (echo and value.ndim in (2, 3)
					and (out_tag == "latent"  # channel count is model-defined
					     or value.ndim == 2 or value.shape[2] in (1, 3, 4))):
				# type-preserving function fed an IMAGE/MASK/LATENT: hand the
				# result back in the caller's format (frame-0 path).
				out.append(polytype.restore(value, out_tag))
			else:
				out.append(value)
		return io.NodeOutput(*out)

	return type(
		node_id,  # already sanitized: 'xphoto.oilPainting' -> cv2_xphoto_oilPainting
		(io.ComfyNode,),
		{
			"define_schema": classmethod(define_schema),
			"execute": classmethod(execute),
		},
	)


def build_nodes(entries=FUNCTIONS):
	"""Node classes for the registry entries the installed OpenCV exposes.

	Entries whose cv2 function is missing are skipped (see _resolve_cv2), so a
	core-only build simply yields fewer nodes instead of failing to import."""
	nodes = []
	for func_name, variant, n_variants, params, returns in entries:
		node = _make_node(func_name, variant, n_variants, params, returns)
		if node is not None:
			nodes.append(node)
	return nodes


# Contrib (submodule) wrappers, built separately so their availability is
# observable: an EMPTY list means the installed cv2 is a core-only build even
# though the stub packages are present (installing opencv-python over
# opencv-contrib-python(-headless) overwrites the shared binary) - run
# tools/repair_opencv_contrib.py. tests/smoke_test.py asserts it is non-empty so
# a silently de-contrib'd environment fails loudly instead of quietly dropping
# every xphoto/ximgproc/bgsegm node from the UI.
CONTRIB_NODES = build_nodes(CONTRIB_FUNCTIONS)

NODES = build_nodes() + CONTRIB_NODES
