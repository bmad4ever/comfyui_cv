def _enum_for(func_name: str, param_name: str, kind: str):
	if kind != "int":
		return None
	return PARAM_ENUMS.get((func_name, param_name)) or PARAM_ENUMS_BY_NAME.get(param_name)


def _build_input(func_name: str, pname: str, kind: str, optional: bool):
	"""Optional parameters are 'advanced' inputs (collapsed in the UI until
	'show advanced inputs'). Curated ones render as properly typed widgets
	preset to the OpenCV default; the rest keep a blank-literal widget where
	blank means 'use the OpenCV default'."""
	enum = _enum_for(func_name, pname, kind)
	tooltip = _tooltip_for(func_name, pname) or " - - - "
	tooltip = tooltip + "\n\n"
	if pname == "dst":
		# cv2 writes the result into the dst array in place; this wrapper
		# hands cv2 a private copy (lowlevel.py:994) so the caller's input
		# array is never mutated - surface that to users who branch on it.
		note = (" The low-level cv2 function writes its result into this array "
		        "in place, but this wrapper passes cv2 a private copy, so your "
		        "input array is never modified.")
		tooltip = (tooltip or "") + note
	advanced = True if optional else None
	if (func_name, pname) in OPTIONAL_BUFFER_PARAMS:
		if (func_name, pname) in DRAWING_DATA_PARAMS | MATH_DATA_PARAMS:
			# data-type optional buffer (e.g. kmeans bestLabels): NPARRAY only,
			# never IMAGE/MASK — poly_input would accept all three.
			return NPArray.Input(pname, optional=True, advanced=True,
				tooltip=(tooltip or f"cv2.{func_name}'s {pname} parameter.")
				+ " Optional - leave unconnected for the OpenCV default (None)."
				+ " A data array (points / matrix), NOT an image - "
				"only an NPARRAY link is accepted here.")
		return polytype.poly_input(pname, optional=True, advanced=True,
			tooltip=(tooltip or f"cv2.{func_name}'s {pname} parameter.")
			+ " Optional - leave unconnected for the OpenCV default (None).")
	if kind == "image":
		if (func_name, pname) in DRAWING_DATA_PARAMS | MATH_DATA_PARAMS:
			# a point set / matrix, not pixels: NPARRAY only, never IMAGE/MASK
			return NPArray.Input(pname, optional=optional, advanced=advanced,
				tooltip=(tooltip or f"cv2.{func_name}'s {pname} parameter.")
				+ " A data array (points / matrix), NOT an image - "
				"only an NPARRAY link is accepted here.")
		if func_name in LATENT_OK and (func_name, pname) not in LATENT_SKIP:
			return polytype.poly_input(pname,
				types=polytype.with_latent(polytype.IMAGEISH),
				optional=optional, advanced=advanced,
				tooltip=(tooltip or "") + polytype.LATENT_NOTE)
		return polytype.poly_input(pname, optional=optional, advanced=advanced,
			tooltip=tooltip)
	if kind == "scalar":
		# one literal string, the same spelling 'CV Scalar' and the curated draw
		# nodes use (scalars.py). Optional scalars (borderValue on remap/warp*/
		# morphology) keep the blank = "OpenCV default" sentinel; required ones
		# (every drawing colour) preset to the all-zero Scalar cv2 itself
		# defaults to, which is what the four split components used to send.
		tip = ((tooltip + " ") if tooltip else "") + scalars.SCALAR_TOOLTIP
		if optional:
			return io.String.Input(pname, default="", placeholder="(default)",
				optional=True, advanced=True,
				tooltip=tip + " Leave blank for the OpenCV default.")
		return io.String.Input(pname, default="(0, 0, 0, 0)",
			placeholder="e.g. (0, 255, 0)", tooltip=tip)
	if isinstance(enum, enums.FlagGroup):
		# base + OR-able bits: a STRING whose value is the pipe-joined constant
		# names. web/cv_flags.js reads the cv_flags spec and renders a base
		# dropdown plus one toggle per flag; headless/API callers and workflows
		# saved when this was a curated combo keep passing the same strings.
		example = enum.default + (f" | {enum.flags[0]}" if enum.flags else "")
		tip = ((tooltip + " ") if tooltip else "") + (
			f"cv2.{func_name} flags: one of {', '.join(enum.options)} plus any of "
			f"{', '.join(enum.flags)}, pipe-joined (e.g. \"{example}\"). In the UI "
			"this renders as a dropdown with one toggle per flag.")
		return io.String.Input(pname, default=enum.initial, optional=optional,
			advanced=advanced, tooltip=tip, extra_dict={"cv_flags": enum.spec()})
	if enum is not None:
		# a curated default may override the generic enum default (e.g. the kernel
		# depth ktype defaults to CV_64F, not DEPTH's "same as input"); it must be
		# a valid option label so the combo still resolves to the OpenCV default.
		override = _default_for(func_name, pname)
		default = override if override in enum.options else enum.default
		return io.Combo.Input(pname, options=enum.options, default=default,
			optional=optional, advanced=advanced,
			tooltip=tooltip or f"OpenCV constant for cv2.{func_name}'s {pname} parameter.")
	if optional:
		default = _default_for(func_name, pname)
		if default is not None:
			tip = ((tooltip + " ") if tooltip else "") + f"Preset to the OpenCV default ({default!r})."
			# the widget range has to CONTAIN the default, or the frontend clamps
			# cv2's own value on the way in (checkRange's +/-DBL_MAX bounds sit
			# far outside the float32-safe 1e38 the other float params use)
			if kind == "int":
				return io.Int.Input(pname, default=default,
					min=min(-INT32_MAX - 1, int(default)),
					max=max(INT32_MAX, int(default)),
					optional=True, advanced=True, tooltip=tip)
			if kind == "float":
				return io.Float.Input(pname, default=float(default),
					min=min(-1e38, float(default)), max=max(1e38, float(default)),
					step=0.00001, optional=True, advanced=True, tooltip=tip)
			if kind == "bool":
				return io.Boolean.Input(pname, default=default, optional=True,
					advanced=True, tooltip=tip)
		tip = ((tooltip + " ") if tooltip else "") + OPTIONAL_TOOLTIP
		return io.String.Input(pname, default="", placeholder="(default)",
			optional=True, advanced=True, tooltip=tip)
	generic = f"Required parameter of cv2.{func_name} - see the OpenCV documentation."
	if kind == "int":
		return io.Int.Input(pname, default=0, min=-INT32_MAX - 1, max=INT32_MAX,
			tooltip=tooltip or generic)
	if kind == "float":
		return io.Float.Input(pname, default=0.0, min=-1e38, max=1e38,
			step=0.00001, tooltip=tooltip or generic)
	if kind == "bool":
		return io.Boolean.Input(pname, default=False, tooltip=tooltip or generic)
	if kind == "str":
		return io.String.Input(pname, default="", tooltip=tooltip or generic)
	if kind == "rotatedrect":
		# the socket takes the CV_ROTATED_RECT a fitEllipse / minAreaRect /
		# CamShift output now emits; the widget stays the literal one, so the
		# value can still be typed and every saved workflow keeps its spelling
		return tuples.RotatedRect.Input(pname,
			placeholder="e.g. ((30, 20), (10, 4), 15)",
			tooltip=((tooltip + " ") if tooltip else "")
			+ "A rotated rectangle: ((center_x, center_y), (width, height), "
			  "angle in degrees). Wire it from cv2.fitEllipse / cv2.minAreaRect "
			  "/ cv2.CamShift, or type the literal (the flat "
			  "(cx, cy, w, h, angle) spelling is accepted too).")
	if kind == "moments":
		return tuples.Moments.Input(pname,
			placeholder="e.g. {'m00': 1.0, 'm10': ...}",
			tooltip=((tooltip + " ") if tooltip else "")
			+ "The NAMED image moments from cv2.moments - wire that node's "
			  "output in. cv2 reads them by name (m00, m10, ...), so a plain "
			  "list of the same numbers would silently give zeros.")
	if kind == "literal" or kind in COMPOSITE_KINDS:
		# a composite param with no split spec renders as the legacy literal widget
		return io.String.Input(pname, default="", placeholder="e.g. (3, 3)",
			tooltip=((tooltip + " ") if tooltip else "") + LITERAL_TOOLTIP)
	return io.AnyType.Input(pname, tooltip=tooltip or generic)  # kind == "any"


