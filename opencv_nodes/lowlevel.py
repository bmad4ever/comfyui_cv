"""Factory that builds V3 node classes for the raw cv2.* function wrappers.

The function metadata lives in registry.py (generated by generator/generator.py
from the cv2 type stubs). For every entry a ComfyNode subclass is created at
import time. Known enum-like integer parameters become dropdowns with the
OpenCV constant names; everything else gets a properly typed widget.

Optional scalar parameters are exposed as string widgets that default to blank,
meaning "use the OpenCV default" - the parameter is then simply not passed.
This avoids guessing defaults that the type stubs do not contain.

registry_contrib.py adds the same metadata for cv2's SUBMODULE functions
(xphoto / ximgproc / bgsegm / img_hash / intensity_transform / ft / motempl /
optflow). Those entries carry a DOTTED name ("xphoto.oilPainting"), which is
resolved with a nested getattr and, crucially, keeps their node ids and display
names distinct from the top-level ones: cv2.inpaint and cv2.xphoto.inpaint are
different algorithms with OPPOSITE mask conventions, so they must never share a
node id. Contrib submodules only exist in opencv-contrib-python(-headless) builds, and the
stub packages are present even when the binary is not, so every entry is probed
against the installed cv2 and skipped when unavailable.
"""

