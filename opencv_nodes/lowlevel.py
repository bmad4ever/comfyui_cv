#
# Exclusion is decided in ONE place, generator/generator.py's
# BLACKLIST = NONFREE | NONSAFE, and applied at GENERATION time: the names below
# are no longer written to registry.py at all, so this filter currently matches
# nothing. It stays because the failure it guards is silent and the cost is a
# set lookup: a registry regenerated from a build whose stubs spell a name
# differently, an entry restored by a bad merge, or a hand-edited registry would
# otherwise expose a wrapper that takes a HOST FILESYSTEM PATH - i.e. let a
# downloaded workflow read (imread), count frames in (imcount) or probe
# (haveImageReader/haveImageWriter) any file on the machine. In ComfyUI images
# arrive through LoadImage, never through these. getBuildInformation is the one
# entry that goes the OTHER way - it takes no path and LEAKS several (the build
# machine's, which on a self-built OpenCV is the user's own); convert.BuildInfo
# serves the same text with them redacted.
#
# If you are here because you removed a function from the generator's NONSAFE
# list and it still does not appear: it is because of this table. Both must
# agree. cv2.imdecode is in neither - it decodes an in-memory buffer, no path.
