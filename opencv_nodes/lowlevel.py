# Whether THIS build can actually run them. cv2 reports it in the build banner;
# without Eigen every EIGEN_GATED function raises "(-213) ... requires OpenCV
# built with the Eigen library" on every call, for every input, so the node says
# so in its description instead of letting the user discover it at execution.
#
# This is read at IMPORT time, not at generation time: the registries are
# regenerated by hand (generator/generator.py) and only carry the EIGEN_GATED
# membership list, but define_schema() runs on every ComfyUI start, so the
# build-specific half below can never go stale against the installed cv2 - swap
# the wheel, restart, and the text follows. (Membership itself IS a generated
# artefact: an OpenCV release that adds or removes an Eigen gate needs a regen.)
HAS_EIGEN = buildinfo.banner_flag(cv2.getBuildInformation(), "Eigen")

