def _split_spec(func_name: str, pname: str, kind: str):
	"""Normalized component spec [(name, default, minimum, is_float, tooltip, enum),
	...] for a param, or None if it is not split. `enum` is an EnumGroup for a
	dropdown component (e.g. TermCriteria's type flag) or None for a plain
	int/float widget. Explicit PARAM_SPLIT wins over the kind-based auto template."""
	explicit = PARAM_SPLIT.get((func_name, pname))
	if explicit is not None:
		return [(name, default, minimum, False, tooltip, None)
		        for name, default, minimum, tooltip in explicit]
	template = _AUTO_SPLIT.get(kind)
	if template is not None:
		override = _SPLIT_DEFAULTS_BY_NAME.get(pname)
		spec = []
		for i, comp in enumerate(template):
			suffix, is_float, default, minimum, tooltip = comp[:5]
			enum = comp[5] if len(comp) > 5 else None
			if override is not None and i < len(override):
				ov = override[i]
				default, tooltip = ov[0], ov[1]
				if len(ov) > 2:
					minimum = ov[2]
			spec.append((pname + suffix, default, minimum, is_float, tooltip, enum))
		return spec
	return None


def _build_split_inputs(spec, optional: bool):
	advanced = True if optional else None
	inputs = []
	for name, default, minimum, is_float, tooltip, enum in spec:
		if enum is not None:
			inputs.append(io.Combo.Input(name, options=enum.options, default=enum.default,
				optional=optional, advanced=advanced, tooltip=tooltip))
		elif is_float:
			inputs.append(io.Float.Input(name, default=float(default), min=float(minimum),
				max=1e38, optional=optional, advanced=advanced, tooltip=tooltip))
		else:
			inputs.append(io.Int.Input(name, default=default, min=minimum, max=INT32_MAX,
				optional=optional, advanced=advanced, tooltip=tooltip))
	return inputs


# Composite kinds that render as ONE atomic CV_TUPLE input (opencv_nodes/tuples.py)
# instead of one widget per component. EMPTY during the foundation pass, so the
# engine below is present but inert - every family still renders exactly as it
# did, and a family is activated by adding its kind here (plus the workflow
# migration for that family). Same staging as the split rollout in a192c9a.
COMPOSITE_INPUT_KINDS = {"size", "point2i", "point2f"}


def _composite_spec(spec, pname):
	"""A normalized split spec -> the CV_TUPLE component dicts + the EnumGroup
	(or None) each component resolves through. Component NAMES are the split
	suffix without the param prefix, so 'dsize_w' becomes 'w' - the param name
	is already on the socket."""
	components, resolvers = [], []
	for name, default, minimum, is_float, tooltip, enum in spec:
		short = name[len(pname):].lstrip("_") if name.startswith(pname) else name
		components.append(tuples.component(
			short, default, minimum, 1e38 if is_float else INT32_MAX,
			is_float, tooltip, enum.options if enum is not None else None))
		resolvers.append(enum)
	return components, resolvers


def _build_composite_input(pname, spec, optional: bool, tooltip: str = None):
	components, _ = _composite_spec(spec, pname)
	names = ", ".join(c["name"] for c in components)
	note = (f" One value with {len(components)} components ({names}) - it travels "
	        f"as a whole, so it cannot arrive half-connected. Wire it from "
	        f"'CV Tuple' or type the components in place.")
	return tuples.CvTuple.Input(pname, components,
		optional=optional, advanced=True if optional else None,
		tooltip=((tooltip + " ") if tooltip else "") + note.strip())


